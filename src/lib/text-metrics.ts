type Metric = {
  size: number;
  table: Record<string, number>;
  tracking: number;
  upper?: boolean;
};

/** Mirrors the .dg-* text rules in src/app/globals.css. Keep in sync. */
export const CLASSES: Record<string, Metric> = {
  "dg-eyebrow": { size: 12, table: BOLD, tracking: 0.08, upper: true },
  "dg-label": { size: 14, table: REGULAR, tracking: 0 },
  "dg-secondary": { size: 12, table: REGULAR, tracking: 0 },
  "dg-note": { size: 12, table: REGULAR, tracking: 0 },
  "dg-note-accent": { size: 12, table: REGULAR, tracking: 0 },
};

/** Rendered width of `text` in px, as drawn by the given .dg-* class. */
export function measure(text: string, className: string): number {
  const metric = CLASSES[className];
  if (!metric) throw new Error(`unknown diagram text class: ${className}`);
  const glyphs = metric.upper ? text.toUpperCase() : text;
  let units = 0;
  for (const ch of glyphs) {
    const width = metric.table[ch];
    if (width === undefined) {
      throw new Error(`no metric for ${JSON.stringify(ch)} in ${className}`);
    }
    units += width;
  }
  // CSS letter-spacing adds after every character, the trailing one included.
  return (units / 1000) * metric.size + metric.tracking * metric.size * glyphs.length;
}
